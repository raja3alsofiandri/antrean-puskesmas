-- ─────────────────────────────────────────────────────────────────────
-- 10. RPC: PENDAFTARAN ANTREAN ATOMIK & IDEMPOTEN
-- ─────────────────────────────────────────────────────────────────────
-- Bersihkan fungsi lama jika ada variasi parameter agar tidak terjadi overload PGRST203
DROP FUNCTION IF EXISTS public.register_queue(UUID, TEXT, TEXT, TEXT);
DROP FUNCTION IF EXISTS public.register_queue(UUID, TEXT, TEXT, TEXT, TEXT);

CREATE OR REPLACE FUNCTION public.register_queue(
    p_tenant_id UUID,
    p_nama TEXT,
    p_sumber TEXT DEFAULT 'ONLINE',
    p_idempotency_key TEXT DEFAULT NULL,
    p_cancel_token_hash TEXT DEFAULT NULL
)
RETURNS TABLE(
    id BIGINT,
    nomor TEXT,
    nama TEXT,
    status TEXT,
    estimasi_menit INTEGER,
    urutan INTEGER,
    panggilan_ke INTEGER,
    is_archived BOOLEAN,
    created_at TIMESTAMPTZ,
    sumber TEXT,
    tenant_id UUID,
    idempotency_key TEXT,
    cancel_token_hash TEXT
)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_next_num INTEGER;
    v_nomor TEXT;
    v_max_urutan INTEGER;
    v_antrean_di_depan INTEGER;
    v_estimasi INTEGER;
    v_existing_id BIGINT;
BEGIN
    -- 1. Idempotensi: kembalikan tiket lama jika kunci idempotensi sudah terdaftar
    IF p_idempotency_key IS NOT NULL AND p_idempotency_key <> '' THEN
        SELECT a.id INTO v_existing_id
        FROM public.antrean a
        WHERE a.tenant_id = p_tenant_id
          AND a.idempotency_key = p_idempotency_key
        LIMIT 1;

        IF v_existing_id IS NOT NULL THEN
            RETURN QUERY 
            SELECT a.id, a.nomor, a.nama, a.status, a.estimasi_menit,
                   a.urutan, a.panggilan_ke, a.is_archived, a.created_at,
                   a.sumber, a.tenant_id, a.idempotency_key, a.cancel_token_hash
            FROM public.antrean a 
            WHERE a.id = v_existing_id;
            RETURN;
        END IF;
    END IF;

    -- 2. Kunci advisory transaksi berdasarkan tenant_id untuk mencegah nomor ganda saat request berbarengan
    PERFORM pg_advisory_xact_lock(hashtext(p_tenant_id::text || '_queue_register'));

    -- 3. Cari nomor urut terbesar hari ini (zona waktu lokal/UTC)
    SELECT COALESCE(MAX(
        CASE WHEN a.nomor ~ '^\D*(\d+)$'
             THEN (regexp_replace(a.nomor, '^\D*', ''))::INTEGER
             ELSE 0 END
    ), 0)
    INTO v_next_num
    FROM public.antrean a
    WHERE a.tenant_id = p_tenant_id
      AND a.created_at::DATE = CURRENT_DATE;

    v_next_num := v_next_num + 1;
    v_nomor := 'A' || LPAD(v_next_num::TEXT, 2, '0');

    -- 4. Hitung urutan tampilan aktif
    SELECT COALESCE(MAX(a.urutan), 0) INTO v_max_urutan
    FROM public.antrean a
    WHERE a.tenant_id = p_tenant_id
      AND a.is_archived = FALSE;

    -- 5. Hitung antrean yang sedang menunggu/dipanggil untuk estimasi awal
    SELECT COUNT(*) INTO v_antrean_di_depan
    FROM public.antrean a
    WHERE a.tenant_id = p_tenant_id
      AND a.is_archived = FALSE
      AND a.status IN ('MENUNGGU', 'MEMANGGIL');

    v_estimasi := GREATEST(5, (v_antrean_di_depan + 1) * 5);

    -- 6. Insert tiket baru
    RETURN QUERY
    INSERT INTO public.antrean (
        nomor, nama, status, estimasi_menit, urutan, panggilan_ke,
        is_archived, sumber, tenant_id, idempotency_key, cancel_token_hash, created_at, updated_at
    ) VALUES (
        v_nomor, p_nama, 'MENUNGGU', v_estimasi, v_max_urutan + 1, 0,
        FALSE, p_sumber, p_tenant_id, p_idempotency_key, p_cancel_token_hash,
        timezone('utc'::text, now()), timezone('utc'::text, now())
    )
    RETURNING
        antrean.id, antrean.nomor, antrean.nama, antrean.status,
        antrean.estimasi_menit, antrean.urutan, antrean.panggilan_ke,
        antrean.is_archived, antrean.created_at, antrean.sumber,
        antrean.tenant_id, antrean.idempotency_key, antrean.cancel_token_hash;
END;
$$;

-- ─────────────────────────────────────────────────────────────────────
-- 11. RPC: PEMBATALAN TIKET ANTREAN DENGAN HASH TOKEN OTORITATIF
-- ─────────────────────────────────────────────────────────────────────
DROP FUNCTION IF EXISTS public.batalkan_tiket_antrean(BIGINT, TEXT, TEXT);

CREATE OR REPLACE FUNCTION public.batalkan_tiket_antrean(
    p_antrean_id BIGINT,
    p_hash_token TEXT,
    p_alasan TEXT DEFAULT 'Dibatalkan oleh pengunjung'
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_tiket RECORD;
    v_now TIMESTAMPTZ := timezone('utc'::text, now());
BEGIN
    SELECT * INTO v_tiket
    FROM public.antrean
    WHERE id = p_antrean_id;

    IF v_tiket IS NULL THEN
        RETURN jsonb_build_object(
            'sukses', false,
            'kode', 'TIDAK_DITEMUKAN',
            'pesan', 'Tiket antrean tidak ditemukan dalam sistem.'
        );
    END IF;

    IF v_tiket.status = 'DIBATALKAN' THEN
        RETURN jsonb_build_object(
            'sukses', false,
            'kode', 'SUDAH_DIBATALKAN',
            'pesan', 'Tiket antrean sudah pernah dibatalkan sebelumnya.'
        );
    END IF;

    IF v_tiket.status = 'SELESAI' THEN
        RETURN jsonb_build_object(
            'sukses', false,
            'kode', 'SUDAH_SELESAI',
            'pesan', 'Tiket tidak dapat dibatalkan karena pelayanan telah selesai.'
        );
    END IF;

    IF v_tiket.status = 'MEMANGGIL' THEN
        RETURN jsonb_build_object(
            'sukses', false,
            'kode', 'SEDANG_DIPANGGIL',
            'pesan', 'Tiket sedang dipanggil ke loket. Konfirmasi langsung ke petugas loket untuk pembatalan.'
        );
    END IF;

    -- Verifikasi hash token rahasia
    IF v_tiket.cancel_token_hash IS NULL OR v_tiket.cancel_token_hash <> p_hash_token THEN
        RETURN jsonb_build_object(
            'sukses', false,
            'kode', 'TOKEN_TIDAK_VALID',
            'pesan', 'Otorisasi gagal: Token pembatalan tidak cocok.'
        );
    END IF;

    -- Update status antrean
    UPDATE public.antrean
    SET status = 'DIBATALKAN',
        waktu_dibatalkan = v_now,
        finished_at = v_now,
        alasan_batal = p_alasan,
        updated_at = v_now
    WHERE id = p_antrean_id;

    -- Update dataset ML
    UPDATE public.ml_dataset
    SET status = 'CANCELLED'
    WHERE antrean_id = p_antrean_id;

    RETURN jsonb_build_object(
        'sukses', true,
        'kode', 'BERHASIL',
        'pesan', 'Tiket antrean nomor ' || v_tiket.nomor || ' berhasil dibatalkan.',
        'nomor', v_tiket.nomor,
        'status', 'DIBATALKAN',
        'waktu_dibatalkan', v_now
    );
END;
$$;

-- ─────────────────────────────────────────────────────────────────────
-- 12. RPC: LOG KEJADIAN PANGGILAN SERVER-SIDE
-- ─────────────────────────────────────────────────────────────────────
DROP FUNCTION IF EXISTS public.log_call_event(BIGINT, INTEGER);

CREATE OR REPLACE FUNCTION public.log_call_event(
    p_antrean_id BIGINT,
    p_panggilan_ke INTEGER DEFAULT 1
)
RETURNS VOID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_tenant_id UUID;
    v_nomor TEXT;
    v_is_first BOOLEAN;
    v_now TIMESTAMPTZ := timezone('utc'::text, now());
BEGIN
    SELECT a.tenant_id, a.nomor INTO v_tenant_id, v_nomor
    FROM public.antrean a
    WHERE a.id = p_antrean_id;

    IF v_tenant_id IS NULL THEN
        RETURN;
    END IF;

    -- Cek panggilan pertama
    v_is_first := NOT EXISTS (
        SELECT 1 FROM public.call_log cl
        WHERE cl.antrean_id = p_antrean_id AND cl.is_first_call = TRUE
    );

    -- Simpan log audit
    INSERT INTO public.call_log (tenant_id, antrean_id, nomor, panggilan_ke, called_at, is_first_call)
    VALUES (v_tenant_id, p_antrean_id, v_nomor, p_panggilan_ke, v_now, v_is_first);

    -- Update dataset ML pada panggilan pertama
    IF v_is_first THEN
        UPDATE public.ml_dataset
        SET first_called_at = v_now,
            waktu_tunggu_menit = ROUND(EXTRACT(EPOCH FROM (v_now - registered_at)) / 60.0, 2),
            status = 'CALLED'
        WHERE antrean_id = p_antrean_id;
    END IF;
END;
$$;

-- ─────────────────────────────────────────────────────────────────────
-- 13. OTOMASI SUPABASE AUTH (auth.users -> tenant_users)
-- ─────────────────────────────────────────────────────────────────────
CREATE OR REPLACE FUNCTION public.handle_new_auth_user()
RETURNS TRIGGER AS $$
BEGIN
    INSERT INTO public.tenant_users (tenant_id, user_id, role, is_active)
    VALUES (
        '00000000-0000-0000-0000-000000000001'::uuid,
        NEW.id,
        COALESCE(NEW.raw_user_meta_data->>'role', 'admin'),
        true
    )
    ON CONFLICT (tenant_id, user_id) DO NOTHING;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
    AFTER INSERT ON auth.users
    FOR EACH ROW EXECUTE FUNCTION public.handle_new_auth_user();

