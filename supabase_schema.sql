-- ==============================================================================
-- SKEMA RESMI DATABASE SUPABASE — SISTEM ANTREAN DIGITAL UNIVERSAL + AI/ML
-- Jalankan skrip ini langsung di: Supabase Dashboard -> SQL Editor -> Run
-- 
-- Fitur Utama:
-- 1. 100% Bebas istilah khusus (universal: organisasi, pengunjung, loket, antrean).
-- 2. Multi-tenant terisolasi dengan Row Level Security (RLS) ketat.
-- 3. Penomoran antrean atomik aman konkurensi & idempoten (advisory lock).
-- 4. Pembatalan tiket terlindungi token rahasia (hash SHA-256).
-- 5. Otentikasi admin via Supabase Auth resmi (auth.users) terintegrasi otomatis.
-- 6. Dataset & riwayat panggilan untuk prediksi waktu tunggu cerdas (AI/ML).
-- 7. Kompatibel Realtime untuk pembaruan instan layar pengunjung & display.
-- ==============================================================================

-- ─────────────────────────────────────────────────────────────────────
-- 0. EKSTENSI DATABASE
-- ─────────────────────────────────────────────────────────────────────
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";
CREATE EXTENSION IF NOT EXISTS "pgcrypto";

-- ─────────────────────────────────────────────────────────────────────
-- 1. TABEL ORGANISASI (TENANTS)
-- ─────────────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public.tenants (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    nama TEXT NOT NULL,
    slug TEXT UNIQUE NOT NULL,
    alamat TEXT DEFAULT '',
    is_active BOOLEAN NOT NULL DEFAULT true,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- Index performa tenants
CREATE INDEX IF NOT EXISTS idx_tenants_slug ON public.tenants(slug);
CREATE INDEX IF NOT EXISTS idx_tenants_active ON public.tenants(is_active);

-- ─────────────────────────────────────────────────────────────────────
-- 2. TABEL PENGGUNA ORGANISASI (TENANT USERS & ROLE)
-- ─────────────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public.tenant_users (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    tenant_id UUID NOT NULL REFERENCES public.tenants(id) ON DELETE CASCADE,
    user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    role TEXT NOT NULL DEFAULT 'admin', -- 'admin' | 'petugas' | 'operator'
    is_active BOOLEAN NOT NULL DEFAULT true,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
    UNIQUE(tenant_id, user_id)
);

CREATE INDEX IF NOT EXISTS idx_tenant_users_lookup ON public.tenant_users(tenant_id, user_id);

-- ─────────────────────────────────────────────────────────────────────
-- 3. TABEL KREDENSIAL PETUGAS (CADANGAN & LOG PERCOBAAN LOGIN)
-- ─────────────────────────────────────────────────────────────────────
